#!/usr/bin/env node
/**
 * compress-data.mjs — 构建期把 data/*.json 压成 gzip+base64，产出 data/compressed.ts
 *
 * 背景（2026-10-15）：上线版面板「点击后几秒才弹出」，包体是主要变量 ——
 * MasterGo 从自家服务器拉 dist/index.html，包体直接决定下载耗时。
 * 且中文词在 esbuild 输出里被 \uXXXX 转义、体积翻倍（164KB → ~280KB）。
 *
 * 收益实测：数据集 535KB → 165KB，中文词 164KB → 48KB（bundle 内）。
 * 运行时用 pako 同步解压（~几十 ms），插件沙箱是纯 JS 环境，无兼容性风险。
 *
 * 产物 compressed.ts **提交进仓库**：CI 的 typecheck 在 build 之前跑，
 * 不提交会导致新 clone 类型检查失败。每次 build 自动重新生成，数据更新后照常提交即可。
 */

import { gzipSync } from 'node:zlib'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const files = {
  DATASET_GZ_B64: 'data/lucide-icons.json',
  ICON_ZH_GZ_B64: 'data/icon-zh.json',
}

let out = `// AUTO-GENERATED by scripts/compress-data.mjs — 请勿手编，npm run build 会重新生成\n`
for (const [name, file] of Object.entries(files)) {
  const gz = gzipSync(readFileSync(join(root, file)), { level: 9 })
  const b64 = gz.toString('base64')
  out += `export const ${name} = "${b64}"\n`
  console.log(`[compress-data] ${file}: ${(gz.length / 1024).toFixed(0)} KB gzip → ${(b64.length / 1024).toFixed(0)} KB base64`)
}

writeFileSync(join(root, 'data', 'compressed.ts'), out)
console.log('[compress-data] ✅ 生成 data/compressed.ts')
